"""Small DB-API bridge for the application's fixed SQLite/PostgreSQL queries."""

import hashlib
import re
import sqlite3
from pathlib import Path
from urllib.parse import quote, urlunsplit

import psycopg
from psycopg.pq import TransactionStatus

from data_analysis_agent.core.errors import ReviewDataError


class DatabaseError(Exception):
    """A database failure safe to display without credentials or SQL values."""


DATABASE_ERRORS = (sqlite3.Error, DatabaseError)


def is_postgres(value):
    return isinstance(value, str) and value.startswith(("postgresql://", "postgres://"))


def database_target(value):
    """Keep DSNs intact; resolve filesystem paths only for SQLite."""
    return value if is_postgres(value) else Path(value).resolve()


def database_identity(value):
    """Stable task binding and display value, independent of login/password."""
    if not is_postgres(value):
        return str(Path(value).resolve())
    try:
        settings = psycopg.conninfo.conninfo_to_dict(value)
        host = settings.get("host", "localhost").lower()
        if ":" in host:
            host = f"[{host}]"
        database = settings.get("dbname")
        if not database:
            raise ValueError
        port = int(settings.get("port", "5432"))
        if not 1 <= port <= 65535:
            raise ValueError
        return urlunsplit(("postgresql", f"{host}:{port}", "/" + quote(database, safe=""), "", ""))
    except (ValueError, psycopg.Error):
        raise ReviewDataError("PostgreSQL 地址必须包含有效的主机、端口和数据库名。") from None


def database_argument(value):
    """CLI: --db env:NAME avoids putting passwords in command lines."""
    if value.startswith("env:"):
        from data_analysis_agent.core.config import read_settings

        name = value[4:]
        value = read_settings().get(name, "")
        if not value:
            raise ValueError(f"请在 .env 或进程环境变量中配置 {name}。")
    if is_postgres(value):
        try:
            database_identity(value)
        except ReviewDataError as exc:
            raise ValueError(str(exc)) from None
    return database_target(value)


class _Row(tuple):
    def __new__(cls, values, names):
        row = super().__new__(cls, values)
        row.names = names
        return row

    def keys(self):
        return self.names

    def __getitem__(self, key):
        return super().__getitem__(self.names.index(key) if isinstance(key, str) else key)


def _row_factory(cursor):
    names = tuple(column.name for column in cursor.description or ())
    return lambda values: _Row(values, names)


def _parameters(query):
    # Only application-owned SQL enters here. Preserve literals, including '?' and '%'.
    parts = re.split(r"('(?:[^']|'')*')", query)
    return "".join(part.replace("%", "%%").replace("?", "%s") if i % 2 == 0
                   else part.replace("%", "%%") for i, part in enumerate(parts))


def postgres_schema(statement):
    statement = re.sub(r"\bid INTEGER PRIMARY KEY\b", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement)
    statement = re.sub(r"\bBLOB\b", "BYTEA", statement)
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement)


class PostgresConnection:
    """Match the transaction/row subset used by the existing fixed SQL statements."""

    def __init__(self, target, *, readonly=False, namespace="business"):
        database_identity(target)
        self.namespace = namespace
        self.readonly = readonly
        self.raw = None
        try:
            self.raw = psycopg.connect(target, autocommit=True, row_factory=_row_factory,
                                       connect_timeout=10, options="-c search_path=public -c timezone=UTC")
            self.raw.execute("SET default_transaction_read_only = " + ("on" if readonly else "off"))
        except psycopg.Error:
            if self.raw is not None:
                self.raw.close()
            raise DatabaseError("PostgreSQL 连接失败，请检查地址、凭据、TLS 和访问权限。") from None

    @property
    def in_transaction(self):
        return self.raw.info.transaction_status != TransactionStatus.IDLE

    def execute(self, query, parameters=None):
        try:
            command = query.strip().upper()
            if command == "BEGIN IMMEDIATE":
                self.raw.execute("BEGIN")
                # Preserve SQLite's serialized read-modify-write transactions across API processes.
                self.raw.execute("SELECT pg_advisory_xact_lock(%s)", (self._lock_key(),))
                return self.raw.cursor()
            if command == "BEGIN":
                query = "BEGIN ISOLATION LEVEL REPEATABLE READ" + (" READ ONLY" if self.readonly else "")
            elif not self.in_transaction and command.startswith(("INSERT", "UPDATE", "DELETE")):
                self.raw.execute("BEGIN")
            if command.startswith("CREATE TABLE"):
                query = postgres_schema(query)
            return self.raw.execute(_parameters(query) if parameters is not None else query, parameters)
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 操作失败，事务未完成；请检查表结构、约束和服务状态。") from None

    def _lock_key(self):
        return int.from_bytes(hashlib.sha256(("review-agent:" + self.namespace).encode()).digest()[:8],
                              "big", signed=True)

    def try_session_lock(self):
        """Acquire this namespace's lock until close(); return False if already held."""
        return bool(self.execute("SELECT pg_try_advisory_lock(?)", (self._lock_key(),)).fetchone()[0])

    def executemany(self, query, rows):
        try:
            if not self.in_transaction:
                self.raw.execute("BEGIN")
            cursor = self.raw.cursor()
            cursor.executemany(_parameters(query), rows)
            return cursor
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 批量写入失败，事务未完成。") from None

    def executescript(self, script):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        try:
            self.raw.commit()
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 提交失败，请核查事务结果。") from None

    def rollback(self):
        try:
            self.raw.rollback()
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 回滚失败，请检查连接。") from None

    def close(self):
        self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        if kind is None:
            self.commit()
        else:
            self.rollback()


def connect_database(target, *, readonly=False, namespace="business", timeout=5):
    """Open an existing database; the caller owns schema checks, transactions and close().

    SQLite files are never created implicitly. Explicit initializers create the
    empty file before calling this factory; PostgreSQL namespaces scope locks.
    """
    if is_postgres(target):
        return PostgresConnection(target, readonly=readonly, namespace=namespace)
    path = Path(target).resolve()
    mode = "ro" if readonly else "rw"
    connection = sqlite3.connect(f"{path.as_uri()}?mode={mode}", uri=True, timeout=timeout)
    try:
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
    except Exception:
        connection.close()
        raise
    return connection


def table_names(connection):
    query = ("SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname='public'"
             if isinstance(connection, PostgresConnection) else
             "SELECT name FROM sqlite_master WHERE type='table'")
    return {row[0] for row in connection.execute(query)}


def insert_id(connection, query, parameters):
    if isinstance(connection, PostgresConnection):
        return connection.execute(query + " RETURNING id", parameters).fetchone()[0]
    return connection.execute(query, parameters).lastrowid


def check_postgres_schema(connection, namespace):
    if "review_database_schema" not in table_names(connection):
        raise ReviewDataError("PostgreSQL 表未初始化，请先执行 review_api_cli init。")
    row = connection.execute("SELECT version FROM review_database_schema WHERE namespace=?", (namespace,)).fetchone()
    if row is None or row[0] != 1:
        raise ReviewDataError("PostgreSQL 数据库版本不支持或未初始化。")


def init_postgres(target, schema, *, namespace="business", context=None):
    from contextlib import closing

    with closing(connect_database(target, namespace=namespace)) as connection, connection:
        connection.execute("BEGIN IMMEDIATE")
        connection.execute("CREATE TABLE IF NOT EXISTS review_database_schema "
                           "(namespace TEXT PRIMARY KEY, version INTEGER NOT NULL)")
        existing = connection.execute("SELECT version FROM review_database_schema WHERE namespace=?", (namespace,)).fetchone()
        if existing:
            check_postgres_schema(connection, namespace)
            return False
        connection.executescript(schema)
        if context is not None:
            connection.execute("INSERT INTO task_context VALUES (?)", (context,))
        connection.execute("INSERT INTO review_database_schema VALUES (?,1)", (namespace,))
        return True
