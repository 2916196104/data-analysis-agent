class DatabaseError(Exception):
    """可安全展示且不包含凭据或 SQL 值的数据库错误。"""


DATABASE_ERRORS = (sqlite3.Error, DatabaseError)


sql_logger = logging.getLogger("data_analysis_agent.sql")
sql_logger.setLevel(logging.WARNING)


def configure_sql_logging(enabled):
    """只记录 SQL 模板和耗时，不展开参数或数据库异常中的业务数据。"""
    sql_logger.setLevel(logging.INFO if enabled else logging.WARNING)


@contextmanager
def _trace_sql(namespace, statement):
    if not sql_logger.isEnabledFor(logging.INFO):
        yield
        return
    started = perf_counter()
    statement = " ".join(statement.split())
    try:
        yield
    except psycopg.Error as exc:
        sql_logger.warning("SQL 失败 范围=%s 耗时=%.2fms 异常=%s | %s",
                           namespace, (perf_counter() - started) * 1000, type(exc).__name__, statement)
        raise
    else:
        sql_logger.info("SQL 成功 范围=%s 耗时=%.2fms | %s",
                        namespace, (perf_counter() - started) * 1000, statement)


def is_postgres(value):
    return isinstance(value, str) and value.startswith(("postgresql://", "postgres://"))


def database_target(value):
    """保持 DSN 完整；仅为 SQLite 解析文件系统路径。"""
    return value if is_postgres(value) else Path(value).resolve()


def database_identity(value):
    """与登录名和密码无关的稳定任务绑定值和展示值。"""
    if not is_postgres(value):
        return str(Path(value).resolve())
    try:
        settings = psycopg.conninfo.conninfo_to_dict(value)
        host = settings.get("host", "localhost").lower()
        if ":" in host:
            host = f"[{host}]"
        database = settings.get("dbname")
        if not database:
            raise ValueError
        port = int(settings.get("port", "5432"))
        if not 1 <= port <= 65535:
            raise ValueError
        return urlunsplit(("postgresql", f"{host}:{port}", "/" + quote(database, safe=""), "", ""))
    except (ValueError, psycopg.Error):
        raise ReviewDataError("PostgreSQL 地址必须包含有效的主机、端口和数据库名。") from None


def database_argument(value):
    """CLI：使用 --db env:NAME，避免把密码放在命令行中。"""
    if value.startswith("env:"):
        from data_analysis_agent.core.config import read_settings

        name = value[4:]
        value = read_settings().get(name, "")
        if not value:
            raise ValueError(f"请在 .env 或进程环境变量中配置 {name}。")
    if is_postgres(value):
        try:
            database_identity(value)
        except ReviewDataError as exc:
            raise ValueError(str(exc)) from None
    return database_target(value)


class _Row(tuple):
    def __new__(cls, values, names):
        row = super().__new__(cls, values)
        row.names = names
        return row

    def keys(self):
        return self.names

    def __getitem__(self, key):
        return super().__getitem__(self.names.index(key) if isinstance(key, str) else key)


def _row_factory(cursor):
    names = tuple(column.name for column in cursor.description or ())
    return lambda values: _Row(values, names)


def _parameters(query):
    # 这里只接收应用自有的 SQL。保留包括 '?' 和 '%' 在内的字面量。
    parts = re.split(r"('(?:[^']|'')*')", query)
    return "".join(part.replace("%", "%%").replace("?", "%s") if i % 2 == 0
                   else part.replace("%", "%%") for i, part in enumerate(parts))


def postgres_schema(statement):
    statement = re.sub(r"\bid INTEGER PRIMARY KEY\b", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement)
    statement = re.sub(r"\bBLOB\b", "BYTEA", statement)
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", statement)


_DEFAULT_POOL_MAX_SIZE = 8
_DEFAULT_POOL_IDLE_SECONDS = 300.0
_DEFAULT_POOL_MAX_LIFETIME_SECONDS = 1800.0
_DEFAULT_POOL_PING_IDLE_SECONDS = 15.0
_DEFAULT_SCHEMA_CACHE_TTL_SECONDS = 60.0

_POOL_LOCK = Lock()
_POOLS: dict[tuple[str, bool, str], "_PostgresPool"] = {}
_POOL_STATS = {"hits": 0, "misses": 0, "discards": 0}
_SCHEMA_CACHE_LOCK = Lock()
_SCHEMA_CACHE: dict[tuple[str, str], float] = {}


def _pool_enabled() -> bool:
    return os.environ.get("DATABASE_POOL_ENABLED", "1").strip().lower() not in ("0", "false", "no", "off")


def _pool_int(name: str, default: int, minimum: int, maximum: int) -> int:
    try:
        value = int(os.environ.get(name, str(default)).strip())
        return max(minimum, min(maximum, value))
    except ValueError:
        return default


def _pool_float(name: str, default: float, minimum: float, maximum: float) -> float:
    try:
        value = float(os.environ.get(name, str(default)).strip())
        return max(minimum, min(maximum, value))
    except ValueError:
        return default


def _schema_cache_ttl() -> float:
    return _pool_float("DATABASE_SCHEMA_CACHE_TTL_SECONDS", _DEFAULT_SCHEMA_CACHE_TTL_SECONDS, 0.0, 3600.0)


def _safe_close_raw(raw) -> None:
    if raw is None:
        return
    try:
        raw.close()
    except Exception:
        pass


class _PostgresPool:
    """线程安全的轻量 PostgreSQL 连接池，按 (target, readonly, namespace) 严格隔离。"""

    def __init__(self, target: str, *, readonly: bool, namespace: str):
        self.target = target
        self.identity = database_identity(target)
        self.readonly = bool(readonly)
        self.namespace = namespace
        self._lock = Lock()
        self._idle: deque[tuple[object, float, float]] = deque()
        self._closed = False

    def acquire(self) -> "PostgresConnection":
        idle_limit = _pool_float("DATABASE_POOL_IDLE_SECONDS", _DEFAULT_POOL_IDLE_SECONDS, 5.0, 3600.0)
        lifetime_limit = _pool_float("DATABASE_POOL_MAX_LIFETIME_SECONDS", _DEFAULT_POOL_MAX_LIFETIME_SECONDS, 30.0, 86400.0)
        ping_after = _pool_float("DATABASE_POOL_PING_IDLE_SECONDS", _DEFAULT_POOL_PING_IDLE_SECONDS, 1.0, 600.0)
        while True:
            with self._lock:
                if self._closed or not self._idle:
                    entry = None
                else:
                    entry = self._idle.pop()
            if entry is None:
                with _POOL_LOCK:
                    _POOL_STATS["misses"] += 1
                return PostgresConnection(self.target, readonly=self.readonly, namespace=self.namespace, _pool=self)
            raw, created_at, last_used = entry
            now = monotonic()
            expired = (now - last_used > idle_limit) or (now - created_at > lifetime_limit)
            unhealthy = (
                getattr(raw, "closed", False) is True
                or getattr(raw, "broken", False) is True
                or raw.info.transaction_status != TransactionStatus.IDLE
            )
            if expired or unhealthy:
                _safe_close_raw(raw)
                with _POOL_LOCK:
                    _POOL_STATS["discards"] += 1
                continue
            if now - last_used >= ping_after:
                try:
                    raw.execute("SELECT 1")
                except Exception:
                    _safe_close_raw(raw)
                    with _POOL_LOCK:
                        _POOL_STATS["discards"] += 1
                    continue
            with _POOL_LOCK:
                _POOL_STATS["hits"] += 1
            return PostgresConnection(
                self.target,
                readonly=self.readonly,
                namespace=self.namespace,
                _raw=raw,
                _pool=self,
                _created_at=created_at,
            )

    def release(self, raw, created_at: float) -> None:
        if raw is None:
            return
        max_size = _pool_int("DATABASE_POOL_MAX_SIZE", _DEFAULT_POOL_MAX_SIZE, 1, 32)
        lifetime_limit = _pool_float("DATABASE_POOL_MAX_LIFETIME_SECONDS", _DEFAULT_POOL_MAX_LIFETIME_SECONDS, 30.0, 86400.0)
        if (
            getattr(raw, "closed", False) is True
            or getattr(raw, "broken", False) is True
            or (monotonic() - created_at > lifetime_limit)
        ):
            _safe_close_raw(raw)
            with _POOL_LOCK:
                _POOL_STATS["discards"] += 1
            return
        try:
            if raw.info.transaction_status != TransactionStatus.IDLE:
                raw.rollback()
            if raw.info.transaction_status != TransactionStatus.IDLE:
                raise psycopg.OperationalError("connection_not_idle")
        except Exception:
            _safe_close_raw(raw)
            with _POOL_LOCK:
                _POOL_STATS["discards"] += 1
            return
        with self._lock:
            if self._closed or len(self._idle) >= max_size:
                _safe_close_raw(raw)
                return
            self._idle.append((raw, created_at, monotonic()))

    def close_idle(self) -> int:
        with self._lock:
            entries = list(self._idle)
            self._idle.clear()
        for raw, _, _ in entries:
            _safe_close_raw(raw)
        return len(entries)


def _get_pool(target: str, *, readonly: bool, namespace: str) -> _PostgresPool:
    key = (target, bool(readonly), namespace)
    with _POOL_LOCK:
        pool = _POOLS.get(key)
        if pool is None:
            pool = _PostgresPool(target, readonly=readonly, namespace=namespace)
            _POOLS[key] = pool
        return pool


def close_database_pools(target=None) -> int:
    """关闭空闲 PostgreSQL 连接池并失效对应 Schema 缓存；传入 target 时仅清理该目标。"""
    target_identity = database_identity(target) if (target is not None and is_postgres(target)) else None
    with _POOL_LOCK:
        selected = [
            (key, pool)
            for key, pool in _POOLS.items()
            if target is None or key[0] == target or (target_identity is not None and pool.identity == target_identity)
        ]
        for key, _ in selected:
            _POOLS.pop(key, None)
    closed = 0
    for _, pool in selected:
        with pool._lock:
            pool._closed = True
        closed += pool.close_idle()
    invalidate_schema_cache(target)
    return closed


def database_pool_stats() -> dict[str, int]:
    """返回连接池只读统计，用于观测连接复用率与测试验证。"""
    with _POOL_LOCK:
        pools = list(_POOLS.values())
        stats = dict(_POOL_STATS)
    idle = 0
    for pool in pools:
        with pool._lock:
            idle += len(pool._idle)
    return {"active_pools": len(pools), "idle_connections": idle, **stats}


def invalidate_schema_cache(target=None, namespace=None) -> None:
    """失效已缓存的 PostgreSQL schema 校验状态。"""
    target_identity = database_identity(target) if (target is not None and is_postgres(target)) else None
    with _SCHEMA_CACHE_LOCK:
        if target is None and namespace is None:
            _SCHEMA_CACHE.clear()
            return
        for key in list(_SCHEMA_CACHE):
            identity, cached_ns = key
            if (target_identity is None or identity == target_identity) and (namespace is None or cached_ns == namespace):
                _SCHEMA_CACHE.pop(key, None)


atexit.register(close_database_pools)


class PostgresConnection:
    """匹配现有固定 SQL 语句使用的事务和行对象子集。"""

    def __init__(self, target, *, readonly=False, namespace="business", _raw=None, _pool=None, _created_at=None):
        identity = database_identity(target)
        self.identity = identity
        self.namespace = namespace
        self.readonly = readonly
        self.read_statement_count = 0
        self._pool = _pool
        self._created_at = monotonic() if _created_at is None else _created_at
        self._closed = False
        self.raw = _raw
        if self.raw is not None:
            return
        try:
            with _trace_sql(self.namespace, "CONNECT " + identity):
                self.raw = psycopg.connect(target, autocommit=True, row_factory=_row_factory,
                                           connect_timeout=10, options="-c search_path=public -c timezone=UTC")
            self._execute("SET default_transaction_read_only = " + ("on" if readonly else "off"))
        except psycopg.Error:
            if self.raw is not None:
                self.raw.close()
            raise DatabaseError("PostgreSQL 连接失败，请检查地址、凭据、TLS 和访问权限。") from None

    @property
    def in_transaction(self):
        return self.raw.info.transaction_status != TransactionStatus.IDLE

    def _execute(self, query, parameters=None):
        if query.lstrip().upper().startswith(('SELECT', 'WITH', 'SHOW')):
            self.read_statement_count = getattr(self, 'read_statement_count', 0) + 1
        with _trace_sql(self.namespace, query):
            return self.raw.execute(query, parameters)

    def execute(self, query, parameters=None):
        try:
            command = query.strip().upper()
            if command == "BEGIN IMMEDIATE":
                self._execute("BEGIN")
                # 在多个 API 进程之间保持 SQLite 序列化的读改写事务。
                self._execute("SELECT pg_advisory_xact_lock(%s)", (self._lock_key(),))
                return self.raw.cursor()
            if command == "BEGIN":
                query = "BEGIN ISOLATION LEVEL REPEATABLE READ" + (" READ ONLY" if self.readonly else "")
            elif not self.in_transaction and command.startswith(("INSERT", "UPDATE", "DELETE")):
                self._execute("BEGIN")
            if command.startswith("CREATE TABLE"):
                query = postgres_schema(query)
            return self._execute(_parameters(query) if parameters is not None else query, parameters)
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 操作失败，事务未完成；请检查表结构、约束和服务状态。") from None

    def _lock_key(self):
        return int.from_bytes(hashlib.sha256(("review-agent:" + self.namespace).encode()).digest()[:8],
                              "big", signed=True)

    def try_session_lock(self):
        """持有此命名空间的锁直到 close()；如果已被占用则返回 False。"""
        return bool(self.execute("SELECT pg_try_advisory_lock(?)", (self._lock_key(),)).fetchone()[0])

    def executemany(self, query, rows):
        try:
            if not self.in_transaction:
                self._execute("BEGIN")
            cursor = self.raw.cursor()
            statement = _parameters(query)
            with _trace_sql(self.namespace, "EXECUTEMANY " + statement):
                cursor.executemany(statement, rows)
            return cursor
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 批量写入失败，事务未完成。") from None

    def executescript(self, script):
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        try:
            with _trace_sql(self.namespace, "COMMIT"):
                self.raw.commit()
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 提交失败，请核查事务结果。") from None

    def rollback(self):
        try:
            with _trace_sql(self.namespace, "ROLLBACK"):
                self.raw.rollback()
        except psycopg.Error:
            raise DatabaseError("PostgreSQL 回滚失败，请检查连接。") from None

    def close(self):
        if self._closed:
            return
        self._closed = True
        raw, pool = self.raw, self._pool
        self._pool = None
        if pool is not None:
            pool.release(raw, self._created_at)
        elif raw is not None:
            raw.close()

    def __enter__(self):
        return self

    def __exit__(self, kind, value, traceback):
        if kind is None:
            self.commit()
        else:
            self.rollback()


def connect_database(target, *, readonly=False, namespace="business", timeout=5, pooled=None):
    """打开已有数据库；数据表检查、事务和 close() 由调用方负责。

    SQLite files are never created implicitly. Explicit initializers create the
    empty file before calling this factory; PostgreSQL namespaces scope locks.
    PostgreSQL connections reuse an in-process pool by default except for
    session-lock worker connections (namespace='worker').
    """
    if is_postgres(target):
        use_pool = (
            _pool_enabled() and namespace != "worker" and psycopg.connect is _REAL_PSYCOPG_CONNECT
            if pooled is None
            else bool(pooled)
        )
        if use_pool:
            return _get_pool(target, readonly=readonly, namespace=namespace).acquire()
        return PostgresConnection(target, readonly=readonly, namespace=namespace)
    path = Path(target).resolve()
    mode = "ro" if readonly else "rw"
    connection = sqlite3.connect(f"{path.as_uri()}?mode={mode}", uri=True, timeout=timeout)
    try:
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
    except Exception:
        connection.close()
        raise
    return connection


def table_names(connection):
    query = ("SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname='public'"
             if isinstance(connection, PostgresConnection) else
             "SELECT name FROM sqlite_master WHERE type='table'")
    return {row[0] for row in connection.execute(query)}


def insert_id(connection, query, parameters):
    if isinstance(connection, PostgresConnection):
        return connection.execute(query + " RETURNING id", parameters).fetchone()[0]
    return connection.execute(query, parameters).lastrowid


def check_postgres_schema(connection, namespace):
    ttl = _schema_cache_ttl()
    identity = getattr(connection, "identity", None)
    if identity and ttl > 0:
        with _SCHEMA_CACHE_LOCK:
            verified_at = _SCHEMA_CACHE.get((identity, namespace))
        if verified_at is not None and monotonic() - verified_at < ttl:
            return
    if "review_database_schema" not in table_names(connection):
        raise ReviewDataError("PostgreSQL 表未初始化，请先执行 review_api_cli init。")
    row = connection.execute("SELECT version FROM review_database_schema WHERE namespace=?", (namespace,)).fetchone()
    if row is None or row[0] != 1:
        raise ReviewDataError("PostgreSQL 数据库版本不支持或未初始化。")
    if identity and ttl > 0:
        with _SCHEMA_CACHE_LOCK:
            _SCHEMA_CACHE[(identity, namespace)] = monotonic()


def init_postgres(target, schema, *, namespace="business", context=None):
    from contextlib import closing

    invalidate_schema_cache(target, namespace)
    with closing(connect_database(target, namespace=namespace, pooled=False)) as connection, connection:
        connection.execute("BEGIN IMMEDIATE")
        connection.execute("CREATE TABLE IF NOT EXISTS review_database_schema "
                           "(namespace TEXT PRIMARY KEY, version INTEGER NOT NULL)")
        existing = connection.execute("SELECT version FROM review_database_schema WHERE namespace=?", (namespace,)).fetchone()
        if existing:
            check_postgres_schema(connection, namespace)
            return False
        connection.executescript(schema)
        if context is not None:
            connection.execute("INSERT INTO task_context VALUES (?)", (context,))
        connection.execute("INSERT INTO review_database_schema VALUES (?,1)", (namespace,))
        return True
